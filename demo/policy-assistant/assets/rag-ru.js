    // Snowball (Porter) stemmer for Russian: endings are cut only after the first vowel (RV),
    // so «отпуск», «отпуска» and «отпуском» meet on one stem.
    function list(withA, plain) {
      const out = [];
      (withA || '').split(' ').forEach((s) => { if (s) out.push([s, true]); });
      (plain || '').split(' ').forEach((s) => { if (s) out.push([s, false]); });
      return out.sort((a, b) => b[0].length - a[0].length);
    }
    const PERFECTIVE = list('в вши вшись', 'ив ивши ившись ыв ывши ывшись');
    const REFLEXIVE = list('', 'ся сь');
    const ADJECTIVE = list('', 'ее ие ые ое ими ыми ей ий ый ой ем им ым ом его ого ему ому их ых ую юю ая яя ою ею');
    const PARTICIPLE = list('ем нн вш ющ щ', 'ивш ывш ующ');
    const VERB = list('ла на ете йте ли й л ем н ло но ет ют ны ть ешь нно',
      'ила ыла ена ейте уйте ите или ыли ей уй ил ыл им ым ен ило ыло ено ят ует уют ит ыт ены ить ыть ишь ую ю');
    const NOUN = list('', 'а ев ов ие ье е иями ями ами еи ии и ией ей ой ий й иям ям ием ем ам ом о у ах иях ях ы ь ию ью ю ия ья я');
    const SUPERLATIVE = list('', 'ейше ейш');
    const DERIVATIONAL = list('', 'ость ост');
    const vowel = (ch) => 'аеиоуыэюя'.indexOf(ch) !== -1;

    function strip(w, start, items) {
      for (const [suffix, afterA] of items) {
        const cut = w.length - suffix.length;
        if (cut < start || w.slice(cut) !== suffix) continue;
        if (afterA) {
          const before = w.charAt(cut - 1);
          if (cut - 1 < start || (before !== 'а' && before !== 'я')) return null;
        }
        return w.slice(0, cut);
      }
      return null;
    }

    // Nouns ending in «-ит» lose it as a verb ending («лимит» → «лим», but «лимиты» → «лимит»): keep them whole.
    const IT_NOUNS = /^(лимит|кредит|визит|депозит|транзит|аппетит)/;

    function stem(word) {
      if (!/[а-я]/.test(word)) return stemEn(word);
      const keep = IT_NOUNS.exec(word);
      if (keep) return keep[1];
      let w = word;
      if (w.length <= 3) return w;
      let rv = 0;
      while (rv < w.length && !vowel(w.charAt(rv))) rv++;
      rv++;
      if (rv >= w.length) return w;
      let r1 = w.length, r2 = w.length;
      for (let i = 1; i < w.length; i++) if (!vowel(w.charAt(i)) && vowel(w.charAt(i - 1))) { r1 = i + 1; break; }
      for (let i = r1 + 1; i < w.length; i++) if (!vowel(w.charAt(i)) && vowel(w.charAt(i - 1))) { r2 = i + 1; break; }
      let cut = strip(w, rv, PERFECTIVE);
      if (cut !== null) w = cut;
      else {
        cut = strip(w, rv, REFLEXIVE);
        if (cut !== null) w = cut;
        cut = strip(w, rv, ADJECTIVE);
        if (cut !== null) {
          const part = strip(cut, rv, PARTICIPLE);
          w = part !== null ? part : cut;
        } else {
          cut = strip(w, rv, VERB);
          if (cut === null) cut = strip(w, rv, NOUN);
          if (cut !== null) w = cut;
        }
      }
      if (w.length - 1 >= rv && w.charAt(w.length - 1) === 'и') w = w.slice(0, -1);
      cut = strip(w, r2, DERIVATIONAL);
      if (cut !== null) w = cut;
      if (/нн$/.test(w) && w.length - 1 >= rv) w = w.slice(0, -1);
      else {
        cut = strip(w, rv, SUPERLATIVE);
        if (cut !== null) { w = cut; if (/нн$/.test(w)) w = w.slice(0, -1); }
        else if (w.charAt(w.length - 1) === 'ь' && w.length - 1 >= rv) w = w.slice(0, -1);
      }
      return w.length >= 2 ? w : word;
    }

    function words(text) {
      return norm(text).replace(/[’'`]/g, '').match(/[a-zа-я0-9£]+(?:[.,][0-9]+)?/g) || [];
    }

